#!/usr/bin/env node
// gen-board-map.mjs — src/platform/s32k396/board_pins.h from calculations/mcu-ballmap.json
// (the rev A.12 pin freeze). Every connected signal ball becomes one binding row plus named
// macros per net: SIUL2 MSCR index (port*32 + pin), peripheral instance and channel.
// Run: node tools/gen-board-map.mjs  (make board-map)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const map = JSON.parse(readFileSync(join(ROOT, "..", "calculations", "mcu-ballmap.json"), "utf8"));
const PORT = { A: 0, B: 1, C: 2, D: 3, E: 4, F: 5, G: 6, H: 7 };

const parse = (fn) => {
  let m;
  if ((m = fn.match(/^ADC(\d)_([PS])(\d+)$/))) return { kind: "BP_ADC", inst: +m[1], chan: +m[3], sub: `'${m[2]}'` };
  if ((m = fn.match(/^SDADC(\d)_AN\[(\d)\]$/))) return { kind: "BP_SDADC", inst: +m[1], chan: +m[2], sub: "'N'" };
  if ((m = fn.match(/^PWM_(\d)_([AB])\[(\d)\]$/))) return { kind: "BP_PWM", inst: +m[1], chan: +m[3], sub: `'${m[2]}'` };
  if ((m = fn.match(/^PWM_(\d)_FAULT\[(\d)\]$/))) return { kind: "BP_PWM_FAULT", inst: +m[1], chan: +m[2], sub: "'F'" };
  if ((m = fn.match(/^CAN(\d)_(TX|RX)$/))) return { kind: "BP_CAN", inst: +m[1], chan: m[2] === "TX" ? 0 : 1, sub: "'C'" };
  if ((m = fn.match(/^LPSPI(\d)_(SOUT|SIN|SCK|PCS0)$/))) return { kind: "BP_LPSPI", inst: +m[1], chan: ["SOUT", "SIN", "SCK", "PCS0"].indexOf(m[2]), sub: "'S'" };
  if ((m = fn.match(/^EIRQ\[(\d+)\]$/))) return { kind: "BP_EIRQ", inst: 0, chan: +m[1], sub: "'E'" };
  if ((m = fn.match(/^FCCU_ERR(\d)$/))) return { kind: "BP_FCCU", inst: 0, chan: +m[1], sub: "'F'" };
  if ((m = fn.match(/^SWG(\d)_(\d)$/))) return { kind: "BP_SWG", inst: +m[1], chan: +m[2], sub: "'W'" };
  if (fn === "") return { kind: "BP_GPIO", inst: 0, chan: 0, sub: "'G'" };
  return { kind: "BP_SYS", inst: 0, chan: 0, sub: "'-'" };
};

const rows = map.balls.filter((b) => b.cls === "signal").map((b) => {
  const p = b.port.match(/^PT([A-H])(\d+)$/);
  return { ...b, ...parse(b.fn), gpio: p ? PORT[p[1]] * 32 + +p[2] : 0xFFFF };
});

const id = (net) => net.replace(/[^A-Za-z0-9]/g, "_").toUpperCase();
const out = [];
out.push(`/* GENERATED by tools/gen-board-map.mjs from calculations/mcu-ballmap.json (rev ${map.rev}) — do not edit.
 * Package: ${map.package}. ${rows.length} signal balls. MSCR index = port*32 + pin (PTA0 = 0 … PTH = 224).
 * ADC channel: sub 'P' = precision input n, 'S' = standard input n (RTD channel index: see
 * s32k396_adc.c, S32K3_ADC_CH()). */
#ifndef BOARD_PINS_H
#define BOARD_PINS_H

#include <stdint.h>

typedef enum { BP_GPIO = 0, BP_ADC, BP_SDADC, BP_PWM, BP_PWM_FAULT, BP_CAN, BP_LPSPI, BP_EIRQ, BP_FCCU, BP_SWG, BP_SYS } bp_kind_t;

typedef struct {
    const char *ball;
    const char *port;
    const char *fn;
    const char *net;
    bp_kind_t kind;
    uint8_t inst;
    uint8_t chan;
    char sub;
    uint16_t mscr;
} bp_entry_t;

#define BOARD_PIN_COUNT ${rows.length}u

#define BOARD_PINS_INIT { \\`);
for (const r of rows) {
  out.push(`    {"${r.ball}", "${r.port}", "${r.fn}", "${r.net}", ${r.kind}, ${r.inst}u, ${r.chan}u, ${r.sub}, ${r.gpio}u}, /* ${r.role.replace(/\*\//g, "")} */ \\`);
}
out.push("}\n");
for (const r of rows) {
  const n = id(r.net);
  out.push(`#define BP_${n}_MSCR ${r.gpio}u`);
  if (r.kind !== "BP_GPIO" && r.kind !== "BP_SYS") {
    out.push(`#define BP_${n}_INST ${r.inst}u`);
    out.push(`#define BP_${n}_CHAN ${r.chan}u`);
  }
}
out.push("\n#endif /* BOARD_PINS_H */\n");
writeFileSync(join(ROOT, "src", "platform", "s32k396", "board_pins.h"), out.join("\n"));
console.log(`board_pins.h: ${rows.length} signal balls`);
