function table(app) {
  const fw = join(app, "Contents", "Frameworks");
  if (!existsSync(fw)) fail(`${fw} does not exist (run macdeployqt first)`);
  const dylibs = readdirSync(fw).filter((f) => f.endsWith(".dylib"));
  const frameworks = readdirSync(fw).filter((f) => f.endsWith(".framework")).map((f) => f.replace(".framework", ""));
  for (const f of frameworks) if (!/^Qt|^qwt$/.test(f)) fail(`${f}.framework is bundled but not covered by NOTICES.md`);
  const seen = new Map();
  for (const d of dylibs) {
    let key = d.replace(/\.dylib$/, "");
    while (/[-.]\d+(\.\d+)*$/.test(key)) key = key.replace(/[-.]\d+(\.\d+)*$/, ""); // libgio-2.0.0 → libgio, libssl.3 → libssl
    let e = LIBS[key];
    if (!e) fail(`${d}: no attribution entry — add it to LIBS in scripts/licences.mjs`);
    if (e.group && !e.f) e = Object.values(LIBS).find((x) => x.group === e.group && x.f);
    seen.set(e.f, e);
  }
  const tp = join(LIC, "third-party");
  mkdirSync(tp, { recursive: true });
  const rows = [];
  for (const [f, e] of [...seen].sort((a, b) => a[1].name.localeCompare(b[1].name))) {
    const keg = realpathSync(brewPrefix(f));
    const version = basename(keg).replace(/_\d+$/, "");
    let text = e.text;
    if (!text) {
      const src = join(keg, e.keg);
      if (!existsSync(src)) fail(`${f}: ${e.keg} not in ${keg}`);
      const dst = `${f.replace(/@.*$/, "")}-${basename(e.keg)}`;
      copyFileSync(src, join(tp, dst));
      text = `third-party/${dst}`;
    }
    rows.push(`| ${e.name} | ${version} | ${e.spdx} | \`${text}\` |`);
  }
  const p = join(QT, "NOTICES.md");
  const s = readFileSync(p, "utf8");
  const a = s.indexOf("<!-- bundled-libraries:begin -->"), b = s.indexOf("<!-- bundled-libraries:end -->");
  if (a < 0 || b < 0) fail("NOTICES.md markers missing");
  const block = `<!-- bundled-libraries:begin -->
| Library (files in \`Contents/Frameworks\`) | Version | Licence (SPDX) | Text |
|---|---|---|---|
${rows.join("\n")}

Table generated by \`scripts/licences.mjs table\` from the staged bundle (${dylibs.length} dylibs, ${frameworks.length} frameworks: ${frameworks.join(", ")}).
`;
  writeFileSync(p, s.slice(0, a) + block + s.slice(b));
  console.log(`  NOTICES.md: ${rows.length} bundled libraries attributed from ${dylibs.length} dylibs`);
}

const [cmd, ...rest] = process.argv.slice(2);
if (cmd === "sources") sources();
else if (cmd === "table") { const i = rest.indexOf("--app"); if (i < 0 || !rest[i + 1]) fail("table needs --app <Traction Tool.app>"); table(resolve(rest[i + 1])); }
else fail("usage: licences.mjs sources [--out <dir>] | table --app <bundle>");
